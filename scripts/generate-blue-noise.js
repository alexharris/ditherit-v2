// One-time generator for 64×64 blue noise threshold map
// Algorithm: void-and-cluster (Ulichney 1993)
// Usage: node scripts/generate-blue-noise.js
// Output: app/utils/blue-noise-texture.ts

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
const __dirname = path.dirname(fileURLToPath(import.meta.url))

const WIDTH = 64
const HEIGHT = 64
const N = WIDTH * HEIGHT // 4096
const SIGMA = 1.5
const KERNEL_RADIUS = Math.ceil(3 * SIGMA) // 5 → 11×11 kernel
const KERNEL_SIZE = 2 * KERNEL_RADIUS + 1
const SEED_FRACTION = 0.1

// Deterministic LCG for reproducible output
let seed = 12345
function rand() {
  seed = (Math.imul(seed, 1664525) + 1013904223) | 0
  return (seed >>> 0) / 0x100000000
}

// Pre-compute 11×11 toroidal Gaussian kernel
const kernel = new Float64Array(KERNEL_SIZE * KERNEL_SIZE)
for (let dy = -KERNEL_RADIUS; dy <= KERNEL_RADIUS; dy++) {
  for (let dx = -KERNEL_RADIUS; dx <= KERNEL_RADIUS; dx++) {
    kernel[(dy + KERNEL_RADIUS) * KERNEL_SIZE + (dx + KERNEL_RADIUS)] =
      Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))
  }
}

// Initialize random binary prototype with ~10% ones
const proto = new Uint8Array(N)
const initialCount = Math.round(N * SEED_FRACTION) // ~410

// Fisher-Yates shuffle to pick seed positions
const positions = Array.from({ length: N }, (_, i) => i)
for (let i = N - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1))
  const tmp = positions[i]; positions[i] = positions[j]; positions[j] = tmp
}
for (let i = 0; i < initialCount; i++) {
  proto[positions[i]] = 1
}

// Maintain energy array: energy[i] = Gaussian-weighted sum of ON pixels near i
const energy = new Float64Array(N)

function updateEnergy(px, py, sign) {
  for (let dy = -KERNEL_RADIUS; dy <= KERNEL_RADIUS; dy++) {
    const ny = ((py + dy) % HEIGHT + HEIGHT) % HEIGHT
    for (let dx = -KERNEL_RADIUS; dx <= KERNEL_RADIUS; dx++) {
      const nx = ((px + dx) % WIDTH + WIDTH) % WIDTH
      energy[ny * WIDTH + nx] +=
        sign * kernel[(dy + KERNEL_RADIUS) * KERNEL_SIZE + (dx + KERNEL_RADIUS)]
    }
  }
}

// Build initial energy from seed pixels
for (let i = 0; i < N; i++) {
  if (proto[i] === 1) updateEnergy(i % WIDTH, Math.floor(i / WIDTH), 1)
}

const rank = new Int32Array(N).fill(-1)

// Phase 1: Remove all ON pixels, rank them from least important (initialCount-1) to most important (0)
// The last removed pixel (in most isolated position) gets rank 0
for (let r = initialCount - 1; r >= 0; r--) {
  // Find tightest cluster: ON pixel with max energy
  let maxE = -Infinity, maxIdx = -1
  for (let i = 0; i < N; i++) {
    if (proto[i] === 1 && energy[i] > maxE) { maxE = energy[i]; maxIdx = i }
  }
  rank[maxIdx] = r
  proto[maxIdx] = 0
  updateEnergy(maxIdx % WIDTH, Math.floor(maxIdx / WIDTH), -1)
}

// Phase 2: Fill remaining OFF pixels, rank them from initialCount to N-1
// Only consider pixels not already ranked by Phase 1 (rank[i] === -1)
// The initial n0 pixels are proto=0 but already ranked — must be excluded
for (let r = initialCount; r < N; r++) {
  // Find largest void: unranked OFF pixel with min energy
  let minE = Infinity, minIdx = -1
  for (let i = 0; i < N; i++) {
    if (rank[i] === -1 && energy[i] < minE) { minE = energy[i]; minIdx = i }
  }
  rank[minIdx] = r
  proto[minIdx] = 1
  updateEnergy(minIdx % WIDTH, Math.floor(minIdx / WIDTH), 1)
}

// Verify all ranks assigned and unique
for (let i = 0; i < N; i++) {
  if (rank[i] === -1) { console.error('ERROR: unranked pixel at', i); process.exit(1) }
}
const rankSet = new Set(Array.from(rank))
if (rankSet.size !== N) { console.error('ERROR: duplicate ranks'); process.exit(1) }

// Scale ranks to uint8: rank 0 → texture 0 (most important, turns on first), rank N-1 → 255
const texture = new Uint8Array(N)
for (let i = 0; i < N; i++) {
  texture[i] = Math.round(rank[i] / (N - 1) * 255)
}

// Format as rows of 64 for readability
const rows = []
for (let y = 0; y < HEIGHT; y++) {
  const row = Array.from(texture.slice(y * WIDTH, (y + 1) * WIDTH)).join(', ')
  rows.push('  ' + row)
}

const output = `// Auto-generated by scripts/generate-blue-noise.js — do not edit manually
// 64×64 tileable blue noise threshold map (void-and-cluster, Ulichney 1993)
// Values are uint8 in [0, 255]. Lower value = turns on first (most isolated position).
export const BLUE_NOISE_TEXTURE: Uint8Array = new Uint8Array([
${rows.join(',\n')}
])
`

const outPath = path.join(__dirname, '..', 'app', 'utils', 'blue-noise-texture.ts')
fs.writeFileSync(outPath, output)
console.log(`Written ${N} values to ${outPath}`)
